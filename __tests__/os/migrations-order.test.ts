// Migration order (factory/dm-crm/prd.md "Migration names"): the folder holds
// names dated in the future, so a new migration must sort after the newest one
// already there, not after today's date. No database (npm run test:migrations
// applies them for real).
import { readdirSync, readFileSync } from "node:fs";
import path from "node:path";
import { execFileSync } from "node:child_process";
import { describe, expect, it } from "vitest";

/** Merged out of order before this check existed; already applied everywhere. */
const LEGACY_OUT_OF_ORDER = ["20261018200000_os_triage_suggested_by", "20261018220000_os_integrations", "20261019020000_os_voice"];

const DIR = path.resolve(__dirname, "../../prisma/migrations");
const names = readdirSync(DIR, { withFileTypes: true })
  .filter((e) => e.isDirectory())
  .map((e) => e.name);

/** Migrations in the order git first saw them (oldest commit first); uncommitted ones last. */
function gitOrder(): string[] | null {
  try {
    const out = execFileSync("git", ["log", "--reverse", "--diff-filter=A", "--name-only", "--format=", "--", "prisma/migrations"], {
      cwd: path.resolve(__dirname, "../.."),
      encoding: "utf8",
      stdio: ["ignore", "pipe", "ignore"],
    });
    const seen: string[] = [];
    for (const line of out.split("\n")) {
      const m = line.match(/^prisma\/migrations\/([^/]+)\/migration\.sql$/);
      if (m && !seen.includes(m[1])) seen.push(m[1]);
    }
    return seen;
  } catch {
    return null;
  }
}

describe("prisma migrations", () => {
  it("every folder is <14-digit timestamp>_<name> with a migration.sql, timestamps unique", () => {
    for (const n of names) {
      expect(n).toMatch(/^\d{14}_[a-z0-9_]+$/);
      expect(readFileSync(path.join(DIR, n, "migration.sql"), "utf8").trim().length).toBeGreaterThan(0);
    }
    const stamps = names.map((n) => n.slice(0, 14));
    expect(new Set(stamps).size).toBe(stamps.length);
  });

  it("each migration sorts after every migration added before it", () => {
    const order = gitOrder();
    if (!order) return; // no git (e.g. a tarball): the name checks above still run
    const added = [...order.filter((n) => names.includes(n)), ...names.filter((n) => !order.includes(n)).sort()];
    const late = added.filter((n, i) => !LEGACY_OUT_OF_ORDER.includes(n) && added.slice(0, i).some((prev) => prev > n));
    expect(late).toEqual([]);
  });

  it("the DM CRM migrations come after the newest one before them (20261026010000)", () => {
    const crm = names.filter((n) => n.includes("_os_crm_"));
    expect(crm.length).toBeGreaterThanOrEqual(4);
    for (const n of crm) expect(n > "20261026010000_os_field_targets").toBe(true);
  });

  it("migration_lock.toml is present and unchanged (provider postgresql)", () => {
    const lock = readFileSync(path.join(DIR, "migration_lock.toml"), "utf8");
    expect(lock).toBe(
      "# Please do not edit this file manually\n# It should be added in your version-control system (e.g., Git)\nprovider = \"postgresql\"\n"
    );
  });
});
